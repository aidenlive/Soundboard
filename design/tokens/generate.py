#!/usr/bin/env python3
"""Generate every token output from obsidian.tokens.json (the OKLCH source of truth).

    python3 design/tokens/generate.py           # write
    python3 design/tokens/generate.py --check   # exit 1 if any output is stale

Inputs:
    design/tokens/obsidian.tokens.json   the pinned system (palette, semantic roles, type, space...)
    public/design/overrides.json         product colour roles for the site (mark, pulse)

Outputs (each carries a "Generated ... do not edit" header):
    platforms/apple/Sources/SoundboardUI/Design/ObsidianTokens.generated.swift
    public/design/tokens.json            every role resolved to oklch(), per theme and accent
    public/design/tokens.css             CSS custom properties; OLED by default, Daylight for light
    public/design/DESIGN.md              the system in DESIGN.md format (frontmatter + prose)

Swift output is plain data. Appearance (theme, accent, waveform) is resolved at runtime by
SemanticPalette.swift, so a token change never requires touching component code.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "design", "tokens", "obsidian.tokens.json")
OVERRIDES = os.path.join(ROOT, "public", "design", "overrides.json")
SWIFT_OUT = os.path.join(ROOT, "platforms", "apple", "Sources", "SoundboardUI", "Design", "ObsidianTokens.generated.swift")
JSON_OUT = os.path.join(ROOT, "public", "design", "tokens.json")
CSS_OUT = os.path.join(ROOT, "public", "design", "tokens.css")
DESIGN_OUT = os.path.join(ROOT, "public", "design", "DESIGN.md")

HEADER = "Generated by design/tokens/generate.py from design/tokens/obsidian.tokens.json. Do not edit."
LIGHT_THEME = "daylight"


def oklch(value):
    m = re.match(r"oklch\(([\d.]+) ([\d.]+) ([\d.]+)\)", value)
    if not m:
        raise ValueError(f"not an oklch() value: {value}")
    return tuple(float(x) for x in m.groups())


def public(d):
    return {k: v for k, v in d.items() if not k.startswith("$")}


# --------------------------------------------------------------------------- resolution

def resolver(tokens, theme, accent, extra=None):
    """Return resolve(ref) for one theme + accent. Mirrors SemanticPalette.swift."""
    sem = tokens["semantic"]
    pal = tokens["palette"]
    family = sem["accents"][accent]["family"]
    scope = {}
    scope.update(sem["always"])
    scope.update(sem["themes"][theme])
    scope.update({k: v for k, v in sem["accents"][accent].items() if k != "family"})
    scope.update(extra or {})

    def resolve(ref, depth=0):
        if depth > 8:
            raise ValueError(f"reference loop at {ref}")
        m = re.fullmatch(r"\{([\w-]+)(?:\.(\d+))?\}", ref)
        if not m:
            return ref
        name, step = m.groups()
        if step is not None:
            fam = family if name == "accent" else name
            if fam not in pal or step not in pal[fam]:
                raise ValueError(f"unknown palette reference {ref}")
            return pal[fam][step]
        if name not in scope:
            raise ValueError(f"unknown semantic reference {ref}")
        return resolve(scope[name], depth + 1)

    return resolve


def resolved_roles(tokens, overrides, theme, accent):
    sem = tokens["semantic"]
    r = resolver(tokens, theme, accent)
    roles = {}
    for group in (sem["always"], sem["themes"][theme], sem["accents"][accent]):
        for k, v in group.items():
            if k.startswith("color-"):
                roles[k] = r(v)
    for k, v in public(overrides.get("colors", {})).items():
        roles[k] = r(v)
    return roles


def resolved_waveforms(tokens, theme, accent):
    out = {}
    for scheme, mapping in tokens["semantic"]["waveforms"].items():
        r = resolver(tokens, theme, accent)
        out[scheme] = {k: r(v) for k, v in mapping.items() if isinstance(v, str)}
        if "deck-b" in mapping:
            out[scheme + "/deck-b"] = {k: r(v) for k, v in mapping["deck-b"].items()}
    return out


# --------------------------------------------------------------------------- swift

def swift_str_map(d, indent="        "):
    items = ",\n".join(f'{indent}"{k}": "{v}"' for k, v in d.items() if not k.startswith("$") and isinstance(v, str))
    return "[\n" + items + "\n    ]" if items else "[:]"


def nested(mapping):
    return swift_str_map(mapping, "            ").replace("\n    ]", "\n        ]")


def swift(tokens):
    sem = tokens["semantic"]
    out = [
        "// " + HEADER,
        "// Change the JSON and run `make tokens`.",
        "",
        "// swiftlint:disable all",
        "public enum ObsidianTokens {",
        "    /// OKLCH palette, keyed \"family.step\" (e.g. \"lime.500\").",
        "    public static let palette: [String: OKLCH] = [",
    ]
    for family, steps in tokens["palette"].items():
        for step, value in steps.items():
            l, c, h = oklch(value)
            out.append(f'        "{family}.{step}": OKLCH({l:.3f}, {c:.3f}, {h:g}),')
    out += ["    ]", "", "    /// Semantic tokens that never change with Appearance.",
            f"    public static let always: [String: String] = {swift_str_map(sem['always'])}", ""]
    for name, group in (("themes", sem["themes"]), ("accents", sem["accents"])):
        out.append(f"    public static let {name}: [String: [String: String]] = [")
        for key, mapping in group.items():
            out.append(f'        "{key}": {nested(mapping)},')
        out += ["    ]", ""]
    out.append("    /// Waveform presets. A \"deck-b\" entry overrides deck B (used by Deck tint).")
    out.append("    public static let waveforms: [String: [String: String]] = [")
    for key, mapping in sem["waveforms"].items():
        base = {k: v for k, v in mapping.items() if isinstance(v, str)}
        out.append(f'        "{key}": {nested(base)},')
        if "deck-b" in mapping:
            out.append(f'        "{key}/deck-b": {nested(mapping["deck-b"])},')
    out.append("    ]")
    custom = sem["waveforms-custom"]
    out += ["",
            f'    public static let customHues: [String] = [{", ".join(chr(34) + h + chr(34) for h in custom["hues"])}]',
            f'    public static let customMinLightnessGap: Double = {custom["minLightnessGap"]}', ""]
    out.append("    /// Spacing scale in points.")
    out.append("    public static let space: [String: Double] = [")
    out += [f'        "{k}": {v},' for k, v in public(tokens["space"]).items()]
    out += ["    ]", "", "    /// Corner radii in points.", "    public static let radius: [String: Double] = ["]
    out += [f'        "{k}": {v},' for k, v in public(tokens["radius"]).items()]
    out += ["    ]", "", "    /// Type roles: (mono, size in points, weight 100-900, tracking).",
            "    public static let typeRoles: [String: (mono: Bool, size: Double, weight: Int, tracking: Double)] = ["]
    for k, v in tokens["typography"]["roles"].items():
        out.append(f'        "{k}": ({str(v["family"] == "mono").lower()}, {v["size"]}, {v["weight"]}, {v["tracking"]}),')
    out += ["    ]", "}"]
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- json + css

def tokens_json(tokens, overrides):
    default = tokens["appearance"]["defaults"]
    sem = tokens["semantic"]
    data = {
        "$generated": HEADER,
        "defaults": {"theme": default["theme"], "accent": default["accent"], "light": LIGHT_THEME},
        "themes": {t: resolved_roles(tokens, overrides, t, default["accent"]) for t in sem["themes"]},
        "accents": {a: {k: resolver(tokens, default["theme"], a)(v)
                        for k, v in m.items() if k.startswith("color-")} for a, m in sem["accents"].items()},
        "waveforms": resolved_waveforms(tokens, default["theme"], default["accent"]),
        "palette": tokens["palette"],
        "typography": {"families": tokens["typography"]["families"], "roles": tokens["typography"]["roles"]},
        "space": public(tokens["space"]),
        "radius": public(tokens["radius"]),
        "elevation": public(tokens["elevation"]),
        "layout": public(overrides.get("layout", {})),
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def css_block(selector, roles, indent="  "):
    lines = [f"{selector} {{"]
    lines += [f"{indent}--{k}: {v};" for k, v in roles.items()]
    lines.append("}")
    return lines


def tokens_css(tokens, overrides):
    default = tokens["appearance"]["defaults"]
    sem = tokens["semantic"]
    fam = tokens["typography"]["families"]
    root = {}
    for family, steps in tokens["palette"].items():
        for step, value in steps.items():
            root[f"palette-{family}-{step}"] = value
    root["font-ui"] = f'"{fam["ui"]}", ui-sans-serif, system-ui, sans-serif'
    root["font-mono"] = f'"{fam["mono"]}", ui-monospace, monospace'
    for role, v in tokens["typography"]["roles"].items():
        root[f"type-{role}-family"] = f"var(--font-{v['family']})"
        root[f"type-{role}-size"] = f"{v['size']}px"
        root[f"type-{role}-weight"] = str(v["weight"])
        root[f"type-{role}-tracking"] = f"{v['tracking'] / v['size']:.3f}em" if v["tracking"] else "0"
    for k, v in public(tokens["space"]).items():
        root[f"space-{k}"] = f"{v}px"
    for k, v in public(tokens["radius"]).items():
        root[f"radius-{k}"] = f"{v}px"
    for k, v in tokens["elevation"]["levels"].items():
        root[f"elevation-{k}"] = f"var(--{v})"
    root["elevation-overlay-shadow"] = tokens["elevation"]["overlay-shadow"]
    for k, v in public(overrides.get("layout", {})).items():
        root[f"layout-{k}"] = f"{v}px"

    out = [f"/* {HEADER} */", "/* Run `make tokens`. Default theme OLED; light follows the system to Daylight. */", ""]
    out += css_block(":root", root)
    out.append("")
    dark = resolved_roles(tokens, overrides, default["theme"], default["accent"])
    light = resolved_roles(tokens, overrides, LIGHT_THEME, default["accent"])
    out += css_block(":root", {"color-scheme": "dark", **dark})
    out += ["", "@media (prefers-color-scheme: light) {"]
    out += css_block("  :root:not([data-theme])", {"color-scheme": "light", **light}, "    ")
    out += ["}", ""]
    for t in sem["themes"]:
        scheme = "light" if t == LIGHT_THEME else "dark"
        out += css_block(f':root[data-theme="{t}"], [data-theme="{t}"]', {"color-scheme": scheme, **resolved_roles(tokens, overrides, t, default["accent"])})
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# --------------------------------------------------------------------------- DESIGN.md

def design_md(tokens, overrides):
    default = tokens["appearance"]["defaults"]
    sem = tokens["semantic"]
    dark = resolved_roles(tokens, overrides, default["theme"], default["accent"])
    light = resolved_roles(tokens, overrides, LIGHT_THEME, default["accent"])
    fam = tokens["typography"]["families"]

    def y(s):
        return '"' + str(s).replace('"', '\\"') + '"'

    fm = ["---", f"# {HEADER}", "name: Obsidian",
          "description: Soundboard's design system. OLED black, three-band spectral waveforms, Geist, one lime accent.",
          "colors:"]
    fm += [f"  {k.removeprefix('color-')}: {y(v)}" for k, v in dark.items()]
    fm.append("typography:")
    for role, v in tokens["typography"]["roles"].items():
        fm += [f"  {role}:", f"    fontFamily: {y(fam[v['family']])}", f"    fontSize: {v['size']}px",
               f"    fontWeight: {v['weight']}"]
        if v["tracking"]:
            fm.append(f"    letterSpacing: {v['tracking'] / v['size']:.3f}em")
    fm.append("rounded:")
    fm += [f"  {k}: {v}px" for k, v in public(tokens["radius"]).items()]
    fm.append("spacing:")
    fm += [f"  {k}: {v}px" for k, v in public(tokens["space"]).items()]
    fm.append("---")

    ext_themes = ["```yaml-extension", "themes:"]
    for t in sem["themes"]:
        ext_themes.append(f"  {t}:")
        ext_themes += [f"    {k.removeprefix('color-')}: {y(v)}" for k, v in resolved_roles(tokens, overrides, t, default["accent"]).items()]
    ext_themes.append("```")
    ext_accents = ["```yaml-extension", "accents:"]
    for a, m in sem["accents"].items():
        r = resolver(tokens, default["theme"], a)
        ext_accents.append(f"  {a}:")
        ext_accents += [f"    {k.removeprefix('color-')}: {y(r(v))}" for k, v in m.items() if k.startswith("color-")]
    ext_accents.append("```")
    ext_wave = ["```yaml-extension", "waveforms:"]
    for scheme, m in resolved_waveforms(tokens, default["theme"], default["accent"]).items():
        ext_wave.append(f"  {scheme}:")
        ext_wave += [f"    {k.removeprefix('color-')}: {y(v)}" for k, v in m.items()]
    custom = sem["waveforms-custom"]
    ext_wave += ["  custom:", f"    hues: [{', '.join(custom['hues'])}]",
                 f"    steps: {{low: {custom['steps']['low']}, mid: {custom['steps']['mid']}, high: {custom['steps']['high']}}}",
                 f"    minLightnessGap: {custom['minLightnessGap']}", "```"]
    ext_elev = ["```yaml-extension", "elevation:"]
    ext_elev += [f"  level-{k}: {v.removeprefix('color-')}" for k, v in tokens["elevation"]["levels"].items()]
    ext_elev += [f"  overlay-shadow: {y(tokens['elevation']['overlay-shadow'])}", "```"]

    opts = tokens["appearance"]["options"]
    body = f"""
# Obsidian

Soundboard's design system. The source is `design/tokens/obsidian.tokens.json`; this file, the
Swift tokens and `tokens.css` are generated from it. Colour is OKLCH only. Components read semantic
roles, never palette steps.

## Overview

A DJ looks at the screen in a dark room, at arm's length, while listening. Obsidian keeps the
background true black on OLED, spends colour only where it means something (frequency bands, cue
slots, status, the one accent), and sets every readout in a monospaced face so digits do not jump.

## Colors

The frontmatter holds the default appearance: theme `{default['theme']}`, accent `{default['accent']}`.
The other themes and accents follow. Light surfaces use `{LIGHT_THEME}`.

{chr(10).join(ext_themes)}

Accents change `primary`, its hover and active states, and the accent waveform scheme. They never
change the brand mark.

{chr(10).join(ext_accents)}

### Waveforms

Waveform colour encodes frequency: low (kick, bass), mid (vocals, snares), high (hats). Every
preset keeps the three bands apart; Deck tint gives deck B its own family. Custom lets the user pick
a hue per band within the guardrail.

{chr(10).join(ext_wave)}

## Typography

{fam['ui']} carries every sentence. {fam['mono']} carries readouts (BPM, time, key, dB) and
eyebrow labels, always with tabular figures. Sizes are points on Apple platforms and pixels on the
site.

## Layout

Spacing comes from the `spacing` scale. Panel padding follows density: comfortable uses `lg`,
compact uses `md`. Deck views: {', '.join(opts['deckView'])}.

## Elevation & Depth

Obsidian is flat. Depth is a lighter surface; only overlays cast a shadow.

{chr(10).join(ext_elev)}

## Shapes

Controls use `rounded.md`; panels `rounded.lg`; pills and pads `rounded.full` or `rounded.xl`.
Hairlines are 1px in `border`.

## Components

Knob (arc, 270°), segmented control, fader, level meter, scrolling and radial deck views, overview
strip, pad grid, the Split mark and Pulse. They live in
`platforms/apple/Sources/SoundboardUI/Components/`.

## Do's and Don'ts

- Do use `primary` for the one action that matters on a view (Mix, Play).
- Do keep waveform bands distinguishable; adjacent bands differ by at least
  {custom['minLightnessGap']} in OKLCH lightness.
- Don't recolour the Split mark with the user's accent; it is always white and Volt lime.
- Don't add a shadow to anything that is not an overlay.
- Don't write a raw colour, size or font in a component.
"""
    return "\n".join(fm) + "\n" + body


# --------------------------------------------------------------------------- main

def outputs():
    tokens = json.load(open(SRC))
    overrides = json.load(open(OVERRIDES)) if os.path.exists(OVERRIDES) else {}
    return {
        SWIFT_OUT: swift(tokens),
        JSON_OUT: tokens_json(tokens, overrides),
        CSS_OUT: tokens_css(tokens, overrides),
        DESIGN_OUT: design_md(tokens, overrides),
    }


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, content in outputs().items():
        current = open(path).read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as f:
                f.write(content)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    if check:
        if stale:
            print("design tokens: stale outputs (run `make tokens`):\n  " + "\n  ".join(stale), file=sys.stderr)
            sys.exit(1)
        print("design tokens: up to date")


if __name__ == "__main__":
    main()
