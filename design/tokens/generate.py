#!/usr/bin/env python3
"""Generate platform token code from obsidian.tokens.json (the OKLCH source of truth).

    python3 design/tokens/generate.py

Writes:
    platforms/apple/Sources/SoundboardUI/Design/ObsidianTokens.generated.swift

The generated code is plain data: the palette as OKLCH values and the semantic mappings
as references ("{lime.500}"). Resolving those references for a given Appearance happens at
runtime (SemanticPalette.swift), so a token change never requires touching component code.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "design", "tokens", "obsidian.tokens.json")
SWIFT_OUT = os.path.join(ROOT, "platforms", "apple", "Sources", "SoundboardUI", "Design", "ObsidianTokens.generated.swift")


def oklch(value):
    m = re.match(r"oklch\(([\d.]+) ([\d.]+) ([\d.]+)\)", value)
    if not m:
        raise ValueError(f"not an oklch() value: {value}")
    return tuple(float(x) for x in m.groups())


def swift_str_map(d, indent="        "):
    items = ",\n".join(f'{indent}"{k}": "{v}"' for k, v in d.items() if not k.startswith("$") and isinstance(v, str))
    return "[\n" + items + "\n    ]" if items else "[:]"


def main():
    tokens = json.load(open(SRC))
    sem = tokens["semantic"]
    out = [
        "// Generated by design/tokens/generate.py from design/tokens/obsidian.tokens.json.",
        "// Do not edit by hand: change the JSON and re-run the generator.",
        "",
        "// swiftlint:disable all",
        "public enum ObsidianTokens {",
        "    /// OKLCH palette, keyed \"family.step\" (e.g. \"lime.500\").",
        "    public static let palette: [String: OKLCH] = [",
    ]
    for family, steps in tokens["palette"].items():
        for step, value in steps.items():
            l, c, h = oklch(value)
            out.append(f'        "{family}.{step}": OKLCH({l:.3f}, {c:.3f}, {h:g}),')
    out.append("    ]")
    out.append("")
    out.append("    /// Semantic tokens that never change with Appearance.")
    out.append(f"    public static let always: [String: String] = {swift_str_map(sem['always'])}")
    out.append("")
    for name, group in (("themes", sem["themes"]), ("accents", sem["accents"])):
        out.append(f"    public static let {name}: [String: [String: String]] = [")
        for key, mapping in group.items():
            out.append(f'        "{key}": {swift_str_map(mapping, "            ").replace(chr(10) + "    ]", chr(10) + "        ]")},')
        out.append("    ]")
        out.append("")
    out.append("    /// Waveform presets. A \"deck-b\" entry overrides deck B (used by Deck tint).")
    out.append("    public static let waveforms: [String: [String: String]] = [")
    for key, mapping in sem["waveforms"].items():
        base = {k: v for k, v in mapping.items() if isinstance(v, str)}
        out.append(f'        "{key}": {swift_str_map(base, "            ").replace(chr(10) + "    ]", chr(10) + "        ]")},')
        if "deck-b" in mapping:
            out.append(f'        "{key}/deck-b": {swift_str_map(mapping["deck-b"], "            ").replace(chr(10) + "    ]", chr(10) + "        ]")},')
    out.append("    ]")
    custom = sem["waveforms-custom"]
    out.append("")
    out.append(f'    public static let customHues: [String] = [{", ".join(chr(34) + h + chr(34) for h in custom["hues"])}]')
    out.append(f'    public static let customMinLightnessGap: Double = {custom["minLightnessGap"]}')
    out.append("}")
    os.makedirs(os.path.dirname(SWIFT_OUT), exist_ok=True)
    with open(SWIFT_OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(SWIFT_OUT, ROOT)} ({sum(len(s) for s in tokens['palette'].values())} palette entries)")


if __name__ == "__main__":
    main()
