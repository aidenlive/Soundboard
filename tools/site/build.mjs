function routingFigure() {
  const d = JSON.parse(read("tools/site/data/routing-session.json"));
  const w = 720, laneH = 64, gap = 28, left = 112, n = d.master.length, bw = (w - left) / n;
  const lane = (vals, y, cls) => vals.map((v, i) => {
    const h = Math.max(1, Math.round(v * laneH));
    return `<rect class="${cls}" x="${(left + i * bw).toFixed(1)}" y="${y + (laneH - h) / 2}" width="${(bw * 0.7).toFixed(1)}" height="${h}"/>`;
  }).join("");
  const y1 = 8, y2 = y1 + laneH + gap, rowH = 14, total = y2 + laneH + 16 + d.events.length * rowH;
  const x = (t) => (left + (t / d.seconds) * (w - left)).toFixed(1);
  const events = d.events.map((e, i) => `<line class="event" x1="${x(e.t)}" x2="${x(e.t)}" y1="${y1 - 4}" y2="${y2 + laneH + 10 + i * rowH}"/><text class="event-label" x="${(+x(e.t) + 4).toFixed(1)}" y="${y2 + laneH + 14 + i * rowH}">${esc(e.label)} · ${e.t} s</text>`).join("");
  return `<figure class="routing-figure">
<svg viewBox="0 0 ${w} ${total}" role="img" aria-label="Peak level of the master and headphone buses over a ${Math.round(d.seconds)}-second session from the routing prototype">
<text class="lane-label" x="0" y="${y1 + laneH / 2 + 4}">Master</text>${lane(d.master, y1, "bar-master")}
<text class="lane-label" x="0" y="${y2 + laneH / 2 + 4}">Headphones</text>${lane(d.headphones, y2, "bar-cue")}
${events}
</svg>
<figcaption>Output of <code>make demo</code>: a ${Math.round(d.seconds)}-second session rendered by the engine. Previewing and cueing track B in the headphones changes the master by 0.000000000: bit-identical.</figcaption>
</figure>`;
}

function fillRegions(html, out, regions) {
  for (const [name, content] of Object.entries(regions)) {
    const re = new RegExp(`(<!-- station:${name} -->)[\\s\\S]*?(<!-- /station:${name} -->)`);
    if (!re.test(html)) throw new Error(`${out}: missing region station:${name}`);
    html = html.replace(re, (_, a, b) => `${a}\n${content}\n${b}`);
  }
  return html;
}

