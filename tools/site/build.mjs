// --------------------------------------------------------------------------- docs

function linker(src, out) {
  return (href) => {
    if (/^(https?:|mailto:|#)/.test(href)) return href;
    const [p, hash] = href.split("#");
    let target = posix.normalize(posix.join(posix.dirname(src), p));
    if (target.endsWith("/")) target = target.slice(0, -1);
    const anchor = hash ? `#${hash}` : "";
    const candidates = [target, `${target}/README.md`];
    for (const c of candidates) {
      const pg = pageBySrc.get(c);
      if (pg) return rel(out, pg.out) + anchor;
    }
    if (target.startsWith("public/") && exists(target)) return rel(out, target.slice("public/".length)) + anchor;
    return null; // a repository file with no page: rendered as code
  };
}

function cApiPage(src) {
  const text = read(src);
  const lines = text.split("\n");
  const intro = text.match(/\/\*([\s\S]*?)\*\//)[1].split("\n").map((l) => l.replace(/^\s*\*\s?/, "")).join("\n").trim();
  const sections = [];
  let cur = { title: "Types", lines: [] };
  for (const line of lines.slice(text.slice(0, text.indexOf("*/") + 2).split("\n").length)) {
    const m = line.match(/^\/\* ---- (.+?) -+ \*\/$/);
    if (m) { sections.push(cur); cur = { title: m[1].trim(), lines: [] }; continue; }
    if (/^#|^extern "C"|^}$|^$/.test(line) && !cur.lines.length) continue;
    if (/^#(ifdef|endif|ifndef|define|include)|^extern "C" \{|^}$/.test(line)) continue;
    cur.lines.push(line);
  }
  sections.push(cur);
  const [title, ...rest] = intro.split("\n");
  let md = `# C API\n\n\`${src}\` is the one boundary between the engine and the platform hosts. ${title.replace(/\.$/, "")}.\n\n\`\`\`\n${rest.join("\n").trim()}\n\`\`\`\n`;
  for (const s of sections) {
    const body = s.lines.join("\n").replace(/^\n+|\n+$/g, "");
    if (body) md += `\n## ${s.title}\n\n\`\`\`c\n${body}\n\`\`\`\n`;
  }
  return md;
}

function docsPage(pg, index) {
  const md = pg.src.endsWith(".h") ? cApiPage(pg.src) : read(pg.src);
  const { html, headings } = render(md, { link: linker(pg.src, pg.out), asset: () => null });
  const h1 = headings.find((h) => h.level === 1);
  pg.title = h1 ? h1.text : pg.src;
  const h2 = headings.filter((h) => h.level === 2);
  const firstPara = (md.split("\n\n").find((b) => b && !b.startsWith("#") && !b.startsWith("|") && !b.startsWith("`")) || NAME).replace(/\s+/g, " ").replace(/[*`[\]]/g, "").slice(0, 160);
  const nav = GROUPS.map((g) => `<div class="nav-group"><h2>${g}</h2><ul>${PAGES.filter((p) => p.group === g).map((p) =>
    `<li><a href="${rel(pg.out, p.out)}"${p === pg ? ' aria-current="page"' : ""}>${esc(p.label || p.navTitle)}</a></li>`).join("")}</ul></div>`).join("");
  const prev = PAGES[index - 1], next = PAGES[index + 1];
  const pn = `<nav class="prev-next" aria-label="Pages">${prev ? `<a class="prev" href="${rel(pg.out, prev.out)}"><span>Previous</span>${esc(prev.label || prev.navTitle)}</a>` : "<span></span>"}${next ? `<a class="next" href="${rel(pg.out, next.out)}"><span>Next</span>${esc(next.label || next.navTitle)}</a>` : "<span></span>"}</nav>`;
  const toc = h2.length ? `<aside class="toc" aria-label="On this page"><h2>On this page</h2><ul>${h2.map((h) => `<li><a href="#${h.id}">${h.text}</a></li>`).join("")}</ul></aside>` : `<aside class="toc"></aside>`;
  const source = `<p class="source">Source: <code>${esc(pg.src)}</code></p>`;
  const body = `<div class="frame docs" id="main">
<input type="checkbox" id="nav-toggle" class="nav-toggle"><label for="nav-toggle" class="nav-toggle-label">Contents</label>
<nav class="sidebar" aria-label="Documentation">${nav}</nav>
<article class="prose">
${html}
${source}
${pn}
</article>
${toc}
</div>`;
  return documentHtml(`public/${pg.out}`.replace(/^public\//, ""), { title: `${pg.title} · ${NAME}`, description: firstPara, current: "docs", body });
}

// Titles first (nav labels need every page's title).
