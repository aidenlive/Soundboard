// Builds the public surface and the root resource page. No dependencies; deterministic.
//
//   node tools/site/build.mjs           write public/ and index.html
//   node tools/site/build.mjs --check   exit 1 if anything would change
//
// Inputs: station.json, CHANGELOG.md, AGENTS.md, docs/**, root Markdown files, .station/STATUS.md,
// engine/include/soundboard/sbe.h, public/design/tokens.json, tools/site/data/*.json, brand/, fonts.
// Writes: public/docs/**, public/design/index.html, public/system/index.html, public/llm.txt,
// public/assets/ (fonts, marks), the marked regions of public/index.html, and index.html.

